// Gera uma planilha Excel (.xlsx) de verdade, direto no navegador, sem biblioteca extra.
// Um .xlsx é um arquivo .zip com alguns XMLs dentro; aqui montamos esse zip "à mão".
//
// downloadXlsx("arquivo.xlsx", [
//   { name: "Vendas", columns: [{ header: "Data", key: "date", type: "date" }, ...], rows: [...] },
// ]);
// Tipos de coluna: "text" (padrão), "number", "money" (R$) e "date" ("AAAA-MM-DD").

const enc = new TextEncoder();

/* ---------- zip (sem compressão) ---------- */
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function zip(files) {
  const parts = [];
  const central = [];
  let offset = 0;
  const now = new Date();
  const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | Math.floor(now.getSeconds() / 2);
  const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();

  for (const f of files) {
    const name = enc.encode(f.name);
    const data = typeof f.data === "string" ? enc.encode(f.data) : f.data;
    const crc = crc32(data);

    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true);
    local.setUint16(4, 20, true);
    local.setUint16(6, 0x0800, true); // nomes em UTF-8
    local.setUint16(8, 0, true); // sem compressão
    local.setUint16(10, dosTime, true);
    local.setUint16(12, dosDate, true);
    local.setUint32(14, crc, true);
    local.setUint32(18, data.length, true);
    local.setUint32(22, data.length, true);
    local.setUint16(26, name.length, true);
    local.setUint16(28, 0, true);
    parts.push(new Uint8Array(local.buffer), name, data);

    const cen = new DataView(new ArrayBuffer(46));
    cen.setUint32(0, 0x02014b50, true);
    cen.setUint16(4, 20, true);
    cen.setUint16(6, 20, true);
    cen.setUint16(8, 0x0800, true);
    cen.setUint16(10, 0, true);
    cen.setUint16(12, dosTime, true);
    cen.setUint16(14, dosDate, true);
    cen.setUint32(16, crc, true);
    cen.setUint32(20, data.length, true);
    cen.setUint32(24, data.length, true);
    cen.setUint16(28, name.length, true);
    cen.setUint32(42, offset, true);
    central.push(new Uint8Array(cen.buffer), name);

    offset += 30 + name.length + data.length;
  }

  const centralSize = central.reduce((s, p) => s + p.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, files.length, true);
  end.setUint16(10, files.length, true);
  end.setUint32(12, centralSize, true);
  end.setUint32(16, offset, true);
  return new Blob([...parts, ...central, new Uint8Array(end.buffer)], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });
}

/* ---------- planilha ---------- */
const esc = (v) =>
  String(v)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    // caracteres de controle quebram o XML
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");

function colName(i) {
  let s = "";
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

// "AAAA-MM-DD" -> número de dias que o Excel usa para datas.
function excelDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso || ""));
  if (!m) return null;
  return (Date.UTC(+m[1], +m[2] - 1, +m[3]) - Date.UTC(1899, 11, 30)) / 86400000;
}

// Estilos: 0 normal | 1 cabeçalho | 2 dinheiro | 3 data
const STYLE = { text: 0, number: 0, money: 2, date: 3 };

function sheetXml({ columns, rows }) {
  const out = [];
  out.push(`<row r="1">${columns.map((c, i) => `<c r="${colName(i)}1" t="inlineStr" s="1"><is><t>${esc(c.header)}</t></is></c>`).join("")}</row>`);
  rows.forEach((row, ri) => {
    const r = ri + 2;
    const cells = columns
      .map((c, ci) => {
        const ref = `${colName(ci)}${r}`;
        const raw = typeof c.value === "function" ? c.value(row) : row[c.key];
        if (raw === null || raw === undefined || raw === "") return "";
        const type = c.type || "text";
        if (type === "number" || type === "money") {
          const n = Number(raw);
          return Number.isFinite(n) ? `<c r="${ref}" s="${STYLE[type]}"><v>${n}</v></c>` : "";
        }
        if (type === "date") {
          const d = excelDate(raw);
          if (d !== null) return `<c r="${ref}" s="3"><v>${d}</v></c>`;
        }
        return `<c r="${ref}" t="inlineStr"><is><t xml:space="preserve">${esc(raw)}</t></is></c>`;
      })
      .join("");
    out.push(`<row r="${r}">${cells}</row>`);
  });

  const widths = columns
    .map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width || Math.max(12, Math.min(48, c.header.length + 6))}" customWidth="1"/>`)
    .join("");
  const lastCol = colName(Math.max(0, columns.length - 1));
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<cols>${widths}</cols>
<sheetData>${out.join("")}</sheetData>
${rows.length ? `<autoFilter ref="A1:${lastCol}${rows.length + 1}"/>` : ""}
</worksheet>`;
}

